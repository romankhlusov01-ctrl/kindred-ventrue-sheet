export function originCatalogById(id: string) {
  return ORIGIN_FEAT_CATALOG.find((f) => f.id === id);
}

export function generalCatalogById(id: string) {
  return GENERAL_FEAT_CATALOG.find((f) => f.id === id);
}

export function generalFeatsForLevel(level: number) {
  return GENERAL_FEAT_CATALOG.filter((f) => f.levelMin <= level);
}

export function recommendedForClan(
  feat: CatalogFeat,
  clan: "ventrue" | "toreador" | string,
) {
  if (!feat.clans?.length) return true;
  if (feat.clans.includes(clan as "ventrue" | "toreador")) return true;
  // Core staples tagged "any" still count as recommended for both clans
  if (feat.clans.includes("any") && feat.tags?.some((t) =>
    ["спас", "концентрация", "хиты", "соц", "навыки", "магия", "удача", "эпик"].includes(t),
  )) {
    return true;
  }
  return false;
}

/** Sort key: clan-recommended first, then any, then other */
export function clanFeatSortKey(
  feat: { id: string; clans?: ("ventrue" | "toreador" | "any")[]; levelMin?: number },
  clan: string,
) {
  if (feat.clans?.includes(clan as "ventrue" | "toreador")) return 0;
  if (!feat.clans || feat.clans.includes("any")) return 1;
  return 2;
}
